"""Request schemas for the settlement API."""
from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field, field_validator

from .timeutil import ensure_hour_aligned_utc


class ReadingIn(BaseModel):
    """One cumulative reading submitted in a batch."""

    meter_id: str = Field(min_length=1, max_length=128)
    hour: datetime = Field(description="Hour mark the cumulative reading refers to (ISO-8601, tz-aware, hour-aligned)")
    cumulative_kwh: float = Field(ge=0, allow_inf_nan=False)
    revision: int = Field(ge=0, description="Revision number; highest revision wins per (meter, hour)")
    reset: bool = Field(default=False, description="True if the meter counter was reset at/before this reading")

    @field_validator("hour")
    @classmethod
    def _hour_aligned(cls, v: datetime) -> datetime:
        try:
            return ensure_hour_aligned_utc(v)
        except ValueError as exc:
            raise ValueError(f"hour: {exc}") from exc


class BatchIn(BaseModel):
    """A batch of backfilled/corrected readings."""

    batch_id: str | None = Field(
        default=None,
        min_length=1,
        max_length=128,
        description="Client-supplied idempotency key; generated by the server when omitted",
    )
    readings: list[ReadingIn] = Field(min_length=1, max_length=10000)
